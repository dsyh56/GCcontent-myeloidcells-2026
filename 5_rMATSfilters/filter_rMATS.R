                 exTxEff %in% c("altCT.protFeat") ~ "altCT.protFeat",
                 exTxEff %in% c("nonCodingEx") ~ "notInCDS",
                 exTxEff %in% c("CDSinframe") ~ "CDSinframe"
                 is.na(exTxEff) ~ "noAnno",
                 TRUE ~ "noAnno"
               ),
               case_when(
                 exTxEff %in% c("NMD.IncFS", "NMD.PTC") ~ "NMD.down",
                 exTxEff %in% c("NMD.SkipFS") ~ "NMD.up",
                 exTxEff %in% c("altProtFeat") ~ "protFeat.down",
                 exTxEff %in% c("FCE.loss") ~ "altFCE",
                 exTxEff %in% c("aCT.ICE", "aCT.LCE") ~ "altCT",
                 exTxEff %in% c("altCT.protFeat") ~ "altCT.protFeat",
                 exTxEff %in% c("nonCodingEx") ~ "notInCDS",
                 exTxEff %in% c("CDSinframe") ~ "CDSinframe",
                 is.na(exTxEff) ~ "noAnno",
                 TRUE ~ "noAnno"
               )
        )
    ) %>%
    arrange(-abs(IncLevelDifference)) %>%#
    filter(!duplicated(coords)) %>%#
    arrange(IncLevelDifference)#
  
  list.res.SE[[i]] <- rmats.proc
  print(paste0("Finished dataset ", i, ":", datasets[i]))
}

