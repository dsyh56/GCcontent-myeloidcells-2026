  )
  
  scores <- log2(
    (wt_5SS$N1[match(substr(X, 4, 4), wt_5SS$Base)] * wt_5SS$N2[match(substr(X, 5, 5), wt_5SS$Base)]) /
      (wt_5SS$bgd[match(substr(X, 4, 4), wt_5SS$Base)] * wt_5SS$bgd[match(substr(X, 5, 5), wt_5SS$Base)]) *
      (me2x5$Value[match(paste0(substr(X, 1, 3), substr(X, 6, 9)), me2x5$Seq)])
  )
  
  if(any.na == TRUE){
    X <- as.vector(matrix(NA, nrow = num_rows))
    X[filled_rows] <- scores
    return(X)
  } else {
    return(scores)
  }
} #for MAXENT 5'ss

switchCoords_0_1 <- function(x){
  index.nonNA <- !is.na(x)
  gr <- GRanges(x[index.nonNA])
  start(gr) <- start(gr)+1
  newCoords <- as.character(gr)
  res <- rep(NA, length(x))
  res[index.nonNA] <- newCoords
  return(res)
} #switch 0-based to 1-based genomic coordinates (for sequence retrieval)


